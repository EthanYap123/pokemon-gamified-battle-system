//////////////////////////////////////////////////////
// GITHUB PAGES DEMO BUILD
// GitHub Pages only serves static files, so this copies public/ into _site/
// and adds an in-browser stand-in for the API (demo/mock-api.js). It reuses
// the real battle engine and the starting data from initTables.js.
// Run: npm run build:demo
//////////////////////////////////////////////////////
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, '_site');

// Modules the browser needs, wrapped so require() works without a bundler
const MODULES = [
    'src/services/battleEngine.js',
    'src/data/baseStats.js',
    'src/data/movesets.js',
    'src/data/typeAdvantage.js',
];

//////////////////////////////////////////////////////
// Read the INSERT statements in initTables.js as rows
//////////////////////////////////////////////////////
function parseValue(token) {
    if (/^NULL$/i.test(token)) return null;
    if (/^TRUE$/i.test(token)) return true;
    if (/^FALSE$/i.test(token)) return false;
    if (/^-?\d+(\.\d+)?$/.test(token)) return Number(token);
    return token;
}

function parseRows(valuesText) {
    const rows = [];
    let row = null;
    let i = 0;
    while (i < valuesText.length) {
        const c = valuesText[i];
        if (c === '-' && valuesText[i + 1] === '-') {
            // comment to end of line
            while (i < valuesText.length && valuesText[i] !== '\n') i++;
        } else if (c === '(' && row === null) {
            row = [];
            i++;
        } else if (c === ')' && row !== null) {
            rows.push(row);
            row = null;
            i++;
        } else if (row !== null && c === "'") {
            let j = i + 1;
            let str = '';
            while (j < valuesText.length) {
                if (valuesText[j] === "'" && valuesText[j + 1] === "'") { str += "'"; j += 2; continue; }
                if (valuesText[j] === "'") break;
                str += valuesText[j++];
            }
            row.push(str);
            i = j + 1;
        } else if (row !== null && /[\w.-]/.test(c)) {
            let j = i;
            while (j < valuesText.length && /[\w.-]/.test(valuesText[j])) j++;
            row.push(parseValue(valuesText.slice(i, j)));
            i = j;
        } else {
            i++;
        }
    }
    return rows;
}

function readSeedTables() {
    const sql = fs.readFileSync(path.join(ROOT, 'src/configs/initTables.js'), 'utf8').replace(/\r\n/g, '\n');
    const tables = {};
    // A statement ends at a ";" followed by an optional "-- comment" and the line end
    const re = /INSERT INTO (\w+) \(([^)]+)\) VALUES\n([\s\S]*?);[ \t]*(?:--[^\n]*)?\n/g;
    let m;
    while ((m = re.exec(sql))) {
        const [, table, colText, valuesText] = m;
        const cols = colText.split(',').map(s => s.trim());
        tables[table] = (tables[table] || []).concat(
            parseRows(valuesText).map(values => Object.fromEntries(cols.map((c, k) => [c, values[k]])))
        );
    }
    return tables;
}

//////////////////////////////////////////////////////
// Build
//////////////////////////////////////////////////////
function copyDir(from, to) {
    fs.mkdirSync(to, { recursive: true });
    for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
        const src = path.join(from, entry.name);
        const dest = path.join(to, entry.name);
        if (entry.isDirectory()) copyDir(src, dest);
        else fs.copyFileSync(src, dest);
    }
}

function bundleModules() {
    const defs = MODULES.map(rel => {
        const code = fs.readFileSync(path.join(ROOT, rel), 'utf8');
        return `${JSON.stringify(rel)}: function (module, exports, require) {\n${code}\n}`;
    }).join(',\n');

    return `// Generated by demo/build.js
(function () {
  var defs = {
${defs}
  };
  var cache = {};
  function resolve(from, request) {
    var parts = from.split('/').slice(0, -1);
    request.split('/').forEach(function (p) {
      if (p === '..') parts.pop();
      else if (p !== '.') parts.push(p);
    });
    var full = parts.join('/');
    return /\\.js$/.test(full) ? full : full + '.js';
  }
  function load(name) {
    if (cache[name]) return cache[name].exports;
    if (!defs[name]) throw new Error('Demo build is missing ' + name);
    var module = { exports: {} };
    cache[name] = module;
    defs[name](module, module.exports, function (request) { return load(resolve(name, request)); });
    return module.exports;
  }
  window.PokemonEngine = load('src/services/battleEngine.js');
  window.PokemonData = {
    baseStats: load('src/data/baseStats.js').baseStats,
    movesets: load('src/data/movesets.js').movesets
  };
})();
`;
}

function injectScripts(htmlDir) {
    const tag = '<script src="../js/queryCmds.js"></script>';
    for (const file of fs.readdirSync(htmlDir).filter(f => f.endsWith('.html'))) {
        const p = path.join(htmlDir, file);
        const html = fs.readFileSync(p, 'utf8');
        if (!html.includes(tag)) throw new Error(`${file} has no queryCmds.js script tag`);
        const scripts =
            '<script src="../demo/demo-data.js"></script>\n' +
            '    <script src="../demo/engine.js"></script>\n' +
            '    <script src="../demo/mock-api.js"></script>\n    ' + tag;
        fs.writeFileSync(p, html.replace(tag, scripts));
    }
}

function build() {
    fs.rmSync(OUT, { recursive: true, force: true });
    copyDir(path.join(ROOT, 'public'), OUT);

    const demoDir = path.join(OUT, 'demo');
    fs.mkdirSync(demoDir, { recursive: true });
    const tables = readSeedTables();
    fs.writeFileSync(path.join(demoDir, 'demo-data.js'), `// Generated by demo/build.js from src/configs/initTables.js\nwindow.DEMO_DATA = ${JSON.stringify(tables)};\n`);
    fs.writeFileSync(path.join(demoDir, 'engine.js'), bundleModules());
    fs.copyFileSync(path.join(__dirname, 'mock-api.js'), path.join(demoDir, 'mock-api.js'));

    injectScripts(path.join(OUT, 'html'));

    // The site root opens the home page
    fs.writeFileSync(path.join(OUT, 'index.html'),
        '<!doctype html><meta charset="utf-8"><title>PokéBattle</title>' +
        '<meta http-equiv="refresh" content="0; url=html/index.html">' +
        '<a href="html/index.html">Open PokéBattle</a>\n');
    fs.writeFileSync(path.join(OUT, '.nojekyll'), '');

    const counts = Object.entries(tables).map(([t, rows]) => `${t}=${rows.length}`).join(' ');
    console.log(`Demo built in _site/ (${counts})`);
}

build();
